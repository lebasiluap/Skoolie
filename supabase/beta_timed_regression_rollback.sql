 result jsonb; replay jsonb; answers jsonb; key text; blocked boolean; activity uuid:=gen_random_uuid(); n integer; deadline timestamptz;
begin
 for u in select id from public.user_profiles loop
  perform set_config('request.jwt.claim.sub',u::text,true);
  exit when not public.is_admin();
 end loop;
 select id into other_u from public.user_profiles where id<>u limit 1;
 select id into admin_u from auth.users where email='lebasiluap@gmail.com';
 select profession into prof from public.user_profiles where id=u;
 select array_agg(id::text) into ids from (select id from public.questions where question_type='mcq' and professions @>array[prof]
  and public.region_visible(region) and access_key is null and correct_answer ~ '^[A-D]$' limit 2)q;
 if cardinality(ids)<>2 then raise exception 'Missing released fixtures'; end if;
 perform set_config('request.jwt.claims',jsonb_build_object('sub',u,'role','authenticated')::text,true);
 set local role authenticated;
 blocked:=false;begin perform public.admin_beta_activity(); exception when insufficient_privilege then blocked:=true;end;
