 reset role;
 perform set_config('request.jwt.claim.sub',u::text,true);
 set local role authenticated;
 issued:=public.begin_verified_timed_session(gen_random_uuid(),'mcq',ids,30);sid:=(issued->>'session_id')::uuid;
