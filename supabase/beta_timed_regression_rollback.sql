 perform public.record_beta_activity(activity,'start','ios','test','0');
 reset role;
 update app_private.beta_activity_sessions set last_seen_at=clock_timestamp()-interval '30 seconds' where id=activity;
 set local role authenticated;
 perform public.record_beta_activity(activity,'beat','ios','test','0');
 reset role;
 select observed_seconds into n from app_private.beta_activity_sessions where id=activity;
 if n not between 30 and 32 then raise exception 'Incorrect foreground duration: %',n;end if;
